def get_words(selection=None):
    """按册+单元选择取词条；selection: {"7a": [1,2,...]}；None/空 = 全部"""
    result = []
    if not selection:
        return list(WORDS)
    for w in WORDS:
        units = selection.get(w["book"])
        if units and w["unit"] in units:
            result.append(w)
    return result

def count_words(selection=None):
    """返回词条总数（可按选择统计）"""
    return len(get_words(selection))
